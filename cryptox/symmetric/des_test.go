var desMode = []cryptox.BlockMode{cryptox.ECB, cryptox.CBC, cryptox.CTR}

type desValue struct {
	key        []byte
	iv         []byte
	plaintext  []byte
	ciphertext []byte
	plaintext2 []byte
}

func (o *desValue) String() string {
	return fmt.Sprintf("Key:{bs=%v};\nIv:{bs=%v};\nPlaintext:{bs=%v};\nCiphertext:{bs=%v};\nPlaintext2:{bs=%v};",
		o.key, o.iv, o.plaintext, o.ciphertext, o.plaintext2)
}

