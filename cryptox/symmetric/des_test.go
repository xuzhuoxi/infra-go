func compareDesCipherResult(t *testing.T, title string, value *desValue, err1, err2 error) {
	if err1 != nil || err2 != nil {
		t.Fatal(title, value, err1, err2)
		return
	}
	if !slicex.EqualUint8(value.plaintext, value.plaintext2) {
		t.Fatal(title, value)
		return
	}
	t.Log(title, value)
}
