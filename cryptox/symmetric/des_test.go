func TestDES(t *testing.T) {
	for _, value := range ivDesCases {
		for _, m := range desMode {
			cipher := NewDESCipher(value.key)
			ciphertext, err1 := cipher.EncryptMode(value.plaintext, m)
			plaintext, err2 := cipher.DecryptMode(ciphertext, m)
			value.ciphertext, value.plaintext2 = ciphertext, plaintext
			compareDesCipherResult(t, string(m), value, err1, err2)
		}
		fmt.Println("---------- ---------- ---------- ---------- ---------- ----------")
	}
}
